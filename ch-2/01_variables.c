
#include <stdio.h>

int main() {
    int i = 10;
    int j = i;

    // %d is called a format specifier
    // %d = int, %f = float, %c = char

    printf("The value of i is %d and value of j is %d\n", i, j);

    int a = 2, b = 5, c = 4, d = 9;

    printf("The value of a is %d and value of b is %d and value of c is %d and value of d is %d\n", a, b, c, d);

    return 0;
}
